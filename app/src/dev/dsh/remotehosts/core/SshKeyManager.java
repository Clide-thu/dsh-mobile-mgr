package dev.dsh.remotehosts.core;

import com.jcraft.jsch.Identity;
import com.jcraft.jsch.JSch;
import com.jcraft.jsch.JSchException;
import com.jcraft.jsch.KeyPair;

import java.io.ByteArrayOutputStream;
import java.nio.charset.Charset;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.time.Instant;
import java.util.Arrays;
import java.util.Base64;
import java.util.Vector;

/**
 * App-managed SSH key pairs: generation, import, and public-key fingerprints
 * (v0.2.0, see docs/app-spec.md §8).
 *
 * Pure Java (JSch + JCA only, no Android imports) so it can be unit-tested on a
 * desktop JVM. Private material is returned inside {@link SshKeyRecord} and must
 * be persisted only through {@link HostStore} (AES-256-GCM / Android Keystore);
 * no method here logs or prints a key.
 *
 * Implementation notes (chosen after probing the bundled JSch 2.28.8):
 *  - generation uses {@code KeyPair.genKeyPair(JSch, KeyPair.RSA, bits)} and
 *    {@code writePrivateKey(out)}: keys generated by the app are unencrypted PEM
 *    (they are protected at rest by the Android Keystore envelope, not by a PEM
 *    passphrase). Imported keys keep whatever format/passphrase they arrived
 *    with.
 *  - import parses the key through {@code JSch.addIdentity}+{@code Identity}
 *    instead of {@code KeyPair.load}: {@code KeyPair.load} silently returns an
 *    undecrypted pair for a wrong passphrase, while {@code addIdentity} reports
 *    "Incorrect passphrase provided." — an explicit, correct
 *    NEEDS_CREDENTIALS signal. It also accepts PKCS#1 PEM, OpenSSH v1
 *    (RSA/ECDSA/ed25519) and PKCS#8 formats from one code path.
 *  - fingerprints are {@code SHA256:}+standard-base64(SHA-256(public key blob))
 *    without "=" padding, exactly the format {@code ssh-keygen -lf <key.pub>}
 *    prints, so users can compare the fingerprint with the server side; JSch's
 *    MD5 {@code getFingerPrint()} is not used.
 */
public final class SshKeyManager {

    private SshKeyManager() {
    }

    /** Default RSA size for generated keys. */
    public static final int DEFAULT_RSA_BITS = 3072;

    private static final Charset UTF8 = Charset.forName("UTF-8");
    private static final SecureRandom RANDOM = new SecureRandom();

    /**
     * Generate a new RSA key pair, returning a fully populated record (including
     * a fresh id and createdAt). {@code rsaBits} must be 2048, 3072 or 4096.
     */
    public static SshKeyRecord generate(String label, int rsaBits) throws AppError {
        if (rsaBits != 2048 && rsaBits != 3072 && rsaBits != 4096) {
            throw AppError.badRequest("RSA 位数只支持 2048 / 3072 / 4096");
        }
        String safeLabel = normalizeLabel(label);
        KeyPair pair = null;
        try {
            pair = KeyPair.genKeyPair(new JSch(), KeyPair.RSA, rsaBits);
            ByteArrayOutputStream privateOut = new ByteArrayOutputStream();
            // No passphrase: the encrypted-at-rest guarantee comes from the
            // Android Keystore envelope around the whole store file.
            pair.writePrivateKey(privateOut);
            byte[] publicBlob = pair.getPublicKeyBlob();
            if (publicBlob == null || publicBlob.length == 0) {
                throw AppError.internal("生成 SSH 密钥失败：公钥数据为空");
            }
            SshKeyRecord record = new SshKeyRecord();
            record.id = newId();
            record.label = safeLabel;
            record.keyType = pair.getKeyTypeString();
            record.privateKey = privateOut.toString(UTF8.name());
            record.passphrase = "";
            record.publicKey = publicKeyLine(record.keyType, publicBlob, safeLabel);
            record.fingerprint = fingerprintOfBlob(publicBlob);
            record.createdAt = Instant.now().toString();
            record.source = "generated";
            return record;
        } catch (AppError error) {
            throw error;
        } catch (Exception error) {
            // JSch/IO failures here cannot contain the freshly generated key in
            // the message, but sanitise anyway and keep the message readable.
            throw AppError.internal("生成 SSH 密钥失败：" + LogSanitizer.sanitizeThrowable(error));
        } finally {
            if (pair != null) {
                try {
                    pair.dispose();
                } catch (RuntimeException ignored) {
                    // Best effort memory hygiene.
                }
            }
        }
    }

    /**
     * Import an existing private key, optionally protected by a passphrase and
     * optionally accompanied by its OpenSSH public key line.
     *
     * @param privateKeyText       PEM/OpenSSH private key text (required)
     * @param passphrase           passphrase for the private key, may be empty
     * @param publicKeyLineOrEmpty full public key line; empty = derive from private key
     * @throws AppError BAD_REQUEST for malformed input or a public/private mismatch;
     *                  NEEDS_CREDENTIALS for a wrong/missing passphrase
     */
    public static SshKeyRecord importKeyPair(
            String label, String privateKeyText, String passphrase, String publicKeyLineOrEmpty)
            throws AppError {
        if (privateKeyText == null || privateKeyText.trim().isEmpty()) {
            throw AppError.badRequest("私钥内容为空");
        }
        if (!looksLikePrivateKey(privateKeyText)) {
            throw AppError.badRequest("私钥格式无法识别：应以 -----BEGIN … PRIVATE KEY----- 开头");
        }
        String safeLabel = normalizeLabel(label);
        String pass = passphrase == null ? "" : passphrase;
        String privateText = normalizePrivateKey(privateKeyText);
        byte[] privateBytes = privateText.getBytes(UTF8);
        byte[] passBytes = pass.isEmpty() ? null : pass.getBytes(UTF8);

        Identity identity = loadIdentity(privateBytes, passBytes, pass, privateText);
        byte[] derivedBlob = identity.getPublicKeyBlob();
        if (derivedBlob == null || derivedBlob.length == 0) {
            // Encrypted key material parsed, but the public part was not available:
            // the caller has to supply the (correct) passphrase first.
            throw AppError.needsCredentials("私钥有口令保护，请输入正确口令");
        }
        String keyType = identity.getAlgName();
        if (keyType == null || keyType.isEmpty()) {
            keyType = "unknown";
        }

        if (publicKeyLineOrEmpty != null && !publicKeyLineOrEmpty.trim().isEmpty()) {
            byte[] suppliedBlob = parsePublicKeyBlob(publicKeyLineOrEmpty);
            if (!Arrays.equals(suppliedBlob, derivedBlob)) {
                throw AppError.badRequest("公钥与私钥不匹配：请检查公钥行是否属于该私钥");
            }
        }

        SshKeyRecord record = new SshKeyRecord();
        record.id = newId();
        record.label = safeLabel;
        record.keyType = keyType;
        record.privateKey = privateText;
        record.passphrase = pass;
        record.publicKey = publicKeyLine(keyType, derivedBlob, safeLabel);
        record.fingerprint = fingerprintOfBlob(derivedBlob);
        record.createdAt = Instant.now().toString();
        record.source = "imported";
        return record;
    }

    /** Compute the {@code SHA256:…} fingerprint of an OpenSSH public key line. */
    public static String fingerprintOfPublicKey(String publicKeyLine) throws AppError {
        return fingerprintOfBlob(parsePublicKeyBlob(publicKeyLine));
    }

    /**
     * {@code SHA256:}+standard-base64(SHA-256(blob)) without padding — identical
     * to {@code ssh-keygen -lf} and to the host-key fingerprints produced by
     * {@link SshTunnelEngine}, so both can be compared with server-side output.
     */
    public static String fingerprintOfBlob(byte[] publicKeyBlob) throws AppError {
        if (publicKeyBlob == null || publicKeyBlob.length == 0) {
            throw AppError.badRequest("公钥数据为空，无法计算指纹");
        }
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(publicKeyBlob);
            return "SHA256:" + Base64.getEncoder().withoutPadding().encodeToString(hash);
        } catch (NoSuchAlgorithmException impossible) {
            throw AppError.internal("本机不支持 SHA-256，无法计算密钥指纹");
        }
    }

    /** Quick structural check used by import UI before attempting to parse. */
    public static boolean looksLikePrivateKey(String text) {
        if (text == null) return false;
        String trimmed = text.trim();
        return trimmed.startsWith("-----BEGIN ") && trimmed.contains("PRIVATE KEY-----");
    }

    /** New random stable id, e.g. {@code key-1a2b3c4d5e6f}. */
    public static String newId() {
        byte[] bytes = new byte[6];
        RANDOM.nextBytes(bytes);
        StringBuilder out = new StringBuilder(16);
        out.append("key-");
        for (byte value : bytes) {
            out.append(Character.forDigit((value >> 4) & 0xF, 16));
            out.append(Character.forDigit(value & 0xF, 16));
        }
        return out.toString();
    }

    // ---------------------------------------------------------------- helpers

    /**
     * Parse a private key through a throw-away JSch identity repository.
     *
     * Wrong passphrase -> NEEDS_CREDENTIALS (JSch says "Incorrect passphrase
     * provided."); structurally unparseable -> BAD_REQUEST; an encrypted key
     * without a passphrase also becomes NEEDS_CREDENTIALS through the
     * {@code isEncrypted()} check.
     */
    private static Identity loadIdentity(byte[] privateBytes, byte[] passBytes, String pass, String privateText)
            throws AppError {
        JSch jsch = new JSch();
        try {
            jsch.addIdentity("import", privateBytes, null, passBytes);
        } catch (JSchException error) {
            String message = error.getMessage() == null ? "" : error.getMessage();
            String lower = message.toLowerCase(java.util.Locale.ROOT);
            String safeMessage = LogSanitizer.sanitize(message, privateText, pass);
            if (lower.contains("passphrase")) {
                throw AppError.needsCredentials("私钥口令错误：" + safeMessage);
            }
            throw AppError.badRequest("私钥格式不受支持或已损坏：" + safeMessage);
        } catch (RuntimeException error) {
            throw AppError.badRequest("私钥无法解析：" + LogSanitizer.sanitizeThrowable(error, privateText, pass));
        }
        Vector<Identity> identities;
        try {
            identities = jsch.getIdentityRepository().getIdentities();
        } catch (RuntimeException error) {
            throw AppError.internal("私钥解析失败：" + LogSanitizer.sanitizeThrowable(error, privateText, pass));
        }
        if (identities == null || identities.isEmpty()) {
            throw AppError.badRequest("私钥无法解析：没有识别出任何密钥");
        }
        Identity identity = identities.get(0);
        if (identity.isEncrypted()) {
            // JSch parses the envelope but cannot use it: passphrase missing or
            // wrong. (Wrong passphrases normally already threw above.)
            throw AppError.needsCredentials(pass.isEmpty()
                    ? "私钥有口令保护，请输入口令"
                    : "私钥口令错误");
        }
        return identity;
    }

    /** The raw public key blob from an OpenSSH public key line. */
    private static byte[] parsePublicKeyBlob(String publicKeyLine) throws AppError {
        if (publicKeyLine == null || publicKeyLine.trim().isEmpty()) {
            throw AppError.badRequest("公钥内容为空");
        }
        String[] tokens = publicKeyLine.trim().split("\\s+");
        if (tokens.length < 2) {
            throw AppError.badRequest("公钥格式无效：应为「类型 base64 [注释]」");
        }
        byte[] blob;
        try {
            String base64 = padBase64(tokens[1]);
            blob = Base64.getDecoder().decode(base64);
        } catch (IllegalArgumentException malformed) {
            throw AppError.badRequest("公钥格式无效：base64 解析失败");
        }
        if (blob.length == 0) {
            throw AppError.badRequest("公钥格式无效：数据为空");
        }
        return blob;
    }

    /** Base64 strings copied from OpenSSH files often lack "=" padding. */
    private static String padBase64(String value) {
        int remainder = value.length() % 4;
        if (remainder == 0) return value;
        StringBuilder padded = new StringBuilder(value);
        for (int index = remainder; index < 4; index += 1) padded.append('=');
        return padded.toString();
    }

    private static String publicKeyLine(String keyType, byte[] publicBlob, String label) {
        String type = keyType == null || keyType.isEmpty() ? "ssh-rsa" : keyType;
        String comment = label == null ? "" : label.trim();
        return type + " " + Base64.getEncoder().encodeToString(publicBlob)
                + (comment.isEmpty() ? "" : " " + comment);
    }

    private static String normalizeLabel(String label) {
        if (label == null) return "app-key";
        String trimmed = label.trim();
        return trimmed.isEmpty() ? "app-key" : trimmed;
    }

    private static String normalizePrivateKey(String privateKeyText) {
        String trimmed = privateKeyText.replace("\r\n", "\n").replace('\r', '\n').trim();
        return trimmed.endsWith("\n") ? trimmed : trimmed + "\n";
    }
}
